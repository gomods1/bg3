"""Collect the game's enum -> display-name maps from its XAML into a Lua table.

    python tools/enum_names.py     # reads extract/Game/**/*.xaml, writes Mod/.../Lua/Game/EnumNames.lua

The UI names enum values with templates like

    <ControlTemplate x:Key="AbilityDisplayName">
        ...<DataTrigger Binding="{Binding Ability}" Value="Strength">
               <Setter TargetName="ShortText" Property="Text" Value="{Binding Source=h..., Converter=...}"/>

This tool records, per template key, the bound property and value -> loca handle:
    EnumNames.AbilityDisplayName = { property = "Ability", values = { Strength = "h...", ... } }
Only handles (identifiers) are stored; text is resolved at runtime in the player's language.
The first template with a given key wins (keys are unique in the game's resource dictionaries).
Triggers in templates without a key (e.g. the spell school names in LearnSpells.xaml) are grouped
per file and bound property, under the key "<file stem>.<property>" ("LearnSpells.ReflectionString").
"""
import glob
import os
import re

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(REPO, "extract", "Game")
OUT = os.path.join(REPO, "Mod", "Mods", "BG3Access", "ScriptExtender", "Lua", "Game", "EnumNames.lua")

HANDLE = r"h[0-9a-g]{8}g[0-9a-g]{4}g[0-9a-g]{4}g[0-9a-g]{4}g[0-9a-g]{12}"
TEMPLATE = re.compile(r"<(ControlTemplate|DataTemplate|Style)\b[^>]*x:Key=\"(\w+)\"[^>]*>(.*?)</\1>", re.S)
TRIGGER = re.compile(r"<DataTrigger\s+Binding=\"\{Binding\s+(?:Path=)?(\w+)\}\"\s+Value=\"(\w+)\"\s*>(.*?)</DataTrigger>", re.S)
# Two-condition triggers (MultiDataTrigger): the second condition names a variant of the map, e.g.
# SpellSchoolTitle with GroupType=Cantrip ("Truco de evocación") or IsSpell=True ("Conjuro de
# evocación niv. [1]", a parameterized string: its first Binding Source is the handle).
MULTI_TRIGGER = re.compile(r"<MultiDataTrigger>\s*<MultiDataTrigger.Conditions>\s*"
                           r"<Condition\s+Binding=\"\{Binding\s+(?:Path=)?(\w+)\}\"\s+Value=\"(\w+)\"\s*/>\s*"
                           r"<Condition\s+Binding=\"\{Binding\s+(?:Path=)?(\w+)\}\"\s+Value=\"(\w+)\"\s*/>\s*"
                           r"</MultiDataTrigger.Conditions>(.*?)</MultiDataTrigger>", re.S)
ANY_HANDLE = re.compile(r"Source=['\"]?(" + HANDLE + ")")
TEXT_SETTER = re.compile(r"Property=\"(?:Text|Content|ls:TextBlockFormatter.SourceText)\"\s+Value=\"\{Binding\s+Source='?(" + HANDLE + ")")


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    maps = {}
    for path in sorted(glob.glob(os.path.join(SRC, "**", "*.xaml"), recursive=True)):
        with open(path, encoding="utf-8-sig", errors="replace") as f:
            src = f.read()
        for m in TEMPLATE.finditer(src):
            key, body = m.group(2), m.group(3)
            if key in maps:
                continue
            prop, values = None, {}
            for t in TRIGGER.finditer(body):
                s = TEXT_SETTER.search(t.group(3))
                if s and (prop is None or prop == t.group(1)):
                    prop = t.group(1)
                    values.setdefault(t.group(2), s.group(1))
            if len(values) >= 2:
                maps[key] = (prop, values, os.path.relpath(path, SRC).replace("\\", "/"))
            variants = {}
            for t in MULTI_TRIGGER.finditer(body):
                h = ANY_HANDLE.search(t.group(5))
                if h and 'Property="Text"' in t.group(5):
                    vkey = f"{key}.{t.group(3)}={t.group(4)}"
                    variants.setdefault(vkey, (t.group(1), {}))[1].setdefault(t.group(2), h.group(1))
            for vkey, (prop, values) in variants.items():
                if len(values) >= 2 and vkey not in maps:
                    maps[vkey] = (prop, values, os.path.relpath(path, SRC).replace("\\", "/"))
        # Unkeyed templates: every text trigger of the file, grouped by the bound property.
        stem = os.path.splitext(os.path.basename(path))[0]
        groups = {}
        for t in TRIGGER.finditer(src):
            s = TEXT_SETTER.search(t.group(3))
            if s:
                groups.setdefault(t.group(1), {}).setdefault(t.group(2), s.group(1))
        for prop, values in groups.items():
            key = f"{stem}.{prop}"
            if len(values) >= 2 and key not in maps:
                maps[key] = (prop, values, os.path.relpath(path, SRC).replace("\\", "/"))
    out = ["-- GENERATED by tools/enum_names.py from the game's XAML. Do not edit.",
           "-- Template key -> { property = bound enum property, values = { EnumValue = loca handle } }.",
           "return {"]
    for key in sorted(maps):
        prop, values, rel = maps[key]
        out.append(f"  [{lua_str(key)}] = {{ -- {rel}")
        out.append(f"    property = {lua_str(prop)},")
        out.append("    values = { " + ", ".join(f"[{lua_str(v)}] = {lua_str(h)}" for v, h in sorted(values.items())) + " },")
        out.append("  },")
    out.append("}")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print(f"{len(maps)} enum maps -> {OUT}")


if __name__ == "__main__":
    main()
