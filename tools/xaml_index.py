"""Index the game's XAML pages into a Lua table the mod uses to name and activate UI elements.

    python tools/xaml_index.py      # reads extract/Game/**/Pages/*.xaml, writes Mod/.../Lua/Game/XamlIndex.lua

For every page (keyed by file stem, e.g. "Eula", "Eula_c"):
    root   = the root element's x:Name (the name the widget has at runtime), if it has one
    context = the root element's ls:UIWidget.ContextName (identifies widgets without x:Name)
    title  = loca handle of the page header (Template="{StaticResource PageHeader}" Tag=...)
    texts  = every static loca handle in document order (static labels only; bound text is not here)
    items  = ordered list of { name = x:Name?, type, label = handle?, command = binding path?,
             param = literal CommandParameter?, paramPath = bound CommandParameter path?,
             paramElement = its ElementName?, boundEvent = input event that presses it? }
             for every element with a static label or a bound command (unnamed ones only if labelled)

Only handles and binding names are stored (identifiers, not game text); the text itself is resolved
at runtime with Ext.Loca.GetTranslatedString, in the player's language.
Extraction first, for each pak in SOURCES: Divine -g bg3 -a extract-package -s Data/<pak>.pak
-d <absolute path>/extract/<pak> -x "*.xaml" (Divine wants an absolute destination).
"""
import glob
import os
import re

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
# Paks in load order: a page in a later one replaces the same page from an earlier one (the mod
# browser and photo mode come from Gustav/GustavX, Patch8 adds lobby and connectivity pages).
# Console overrides (GUI/Override/Clairmont) are left out.
SOURCES = ["Game", "Gustav", "GustavX", "Patch8_HotFix9"]
OUT = os.path.join(REPO, "Mod", "Mods", "BG3Access", "ScriptExtender", "Lua", "Game", "XamlIndex.lua")

HANDLE = re.compile(r"Source='(h[0-9a-g]{8}g[0-9a-g]{4}g[0-9a-g]{4}g[0-9a-g]{4}g[0-9a-g]{12})'")
TAG = re.compile(r"<([A-Za-z_][\w.:]*)((?:\s+[\w.:]+\s*=\s*\"[^\"]*\")*)\s*/?>", re.S)
ATTR = re.compile(r"([\w.:]+)\s*=\s*\"([^\"]*)\"")
LABEL_ATTRS = ("Content", "Text", "ls:TextBlockFormatter.SourceText", "Header", "Tag", "ToolTip", "Title")


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def index_file(path):
    with open(path, encoding="utf-8-sig", errors="replace") as f:
        src = f.read()
    page = {"root": None, "context": None, "title": None, "texts": [], "items": []}
    seen = set()
    first = True
    for m in TAG.finditer(src):
        tag, attrs_src = m.group(1), m.group(2)
        attrs = dict(ATTR.findall(attrs_src))
        name = attrs.get("x:Name")
        if first and not tag.startswith("?"):
            first = False
            page["root"] = name
            page["context"] = attrs.get("ls:UIWidget.ContextName")
        for v in attrs.values():
            for h in HANDLE.findall(v):
                if h not in seen:
                    seen.add(h)
                    page["texts"].append(h)
        if page["title"] is None and "PageHeader" in attrs.get("Template", ""):
            hs = HANDLE.findall(attrs.get("Tag", ""))
            if hs:
                page["title"] = hs[0]
        el = {"type": tag}
        if name:
            el["name"] = name
        for a in LABEL_ATTRS:
            hs = HANDLE.findall(attrs.get(a, ""))
            if hs:
                el["label"] = hs[0]
                break
        cm = re.match(r"\{Binding\s+(?:Path=)?([\w.]+)", attrs.get("Command", ""))
        if cm:
            el["command"] = cm.group(1)
        cp = attrs.get("CommandParameter")
        if cp is not None and not cp.startswith("{"):
            el["param"] = cp
        elif cp is not None:
            # {Binding}, {Binding .}, {Binding Path}, {Binding Path, ElementName=X}
            pm = re.match(r"\{Binding\s*(?:Path=)?([\w.]*)\s*(?:,\s*ElementName=(\w+))?\s*\}", cp)
            if pm:
                el["paramPath"] = pm.group(1) or "."
                if pm.group(2):
                    el["paramElement"] = pm.group(2)
            else:
                el["paramPath"] = "?"  # a binding the mod cannot resolve: do not execute with nil
        if attrs.get("BoundEvent") and not attrs["BoundEvent"].startswith("{"):
            el["boundEvent"] = attrs["BoundEvent"]
        if "label" in el or ("command" in el and name):
            page["items"].append(el)
    return page


def main():
    pages = {}
    for pak in SOURCES:
        root = os.path.join(REPO, "extract", pak)
        for path in sorted(glob.glob(os.path.join(root, "**", "Pages", "*.xaml"), recursive=True)):
            rel = os.path.relpath(path, root).replace("\\", "/")
            if "/Override/" in "/" + rel:
                continue
            pages[os.path.splitext(os.path.basename(path))[0]] = (path, pak + "/" + rel)
    files = [pages[k] for k in sorted(pages)]
    out = ["-- GENERATED by tools/xaml_index.py from the game's XAML. Do not edit.",
           "-- Handles resolve with Ext.Loca.GetTranslatedString; see the tool's docstring.",
           "return {"]
    for path, rel in files:
        stem = os.path.splitext(os.path.basename(path))[0]
        p = index_file(path)
        out.append(f"  [{lua_str(stem)}] = {{")
        out.append(f"    file = {lua_str(rel)},")
        if p["root"]:
            out.append(f"    root = {lua_str(p['root'])},")
        if p["context"]:
            out.append(f"    context = {lua_str(p['context'])},")
        if p["title"]:
            out.append(f"    title = {lua_str(p['title'])},")
        out.append("    texts = {" + ", ".join(lua_str(h) for h in p["texts"]) + "},")
        out.append("    items = {")
        for el in p["items"]:
            fields = ", ".join(f"{k} = {lua_str(v)}" for k, v in el.items())
            out.append(f"      {{ {fields} }},")
        out.append("    },")
        out.append("  },")
    out.append("}")
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out) + "\n")
    print(f"{len(files)} pages -> {OUT} ({os.path.getsize(OUT) // 1024} KB)")


if __name__ == "__main__":
    main()
