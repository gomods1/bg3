-- Core/Strings: plural forms, lists, sentences, numbers, language fallback.
local Strings = Ext.Require("Core/Strings.lua")

T.case("English plural forms", function()
    Strings.SetLanguage("en")
    T.eq(Strings.Get("combat_started", { n = 1 }), "Combat: 1 enemy")
    T.eq(Strings.Get("combat_started", { n = 3 }), "Combat: 3 enemies")
    T.eq(Strings.Get("meters", { n = 1 }), "1 meter")
    T.eq(Strings.Get("meters", { n = 1.5 }), "1.5 meters", "fractions take the other form")
    T.eq(Strings.Get("meters", { n = 1.04 }), "1 meter", "spoken with one decimal: 1.04 is 1")
end)

T.case("Spanish table and decimal separator", function()
    T.eq(Strings.SetLanguage("es"), "es")
    T.eq(Strings.Get("loaded", { key = "Control M" }), "BG3 Access cargado. Control M abre el menú del mod.")
    T.eq(Strings.Number(2.25, 2), "2,25")
    T.eq(Strings.Number(2.0, 2), "2")
    T.eq(Strings.Get("meters", { n = 2.5 }), "2,5 metros", "numbers in placeholders use the language's separator")
    T.eq(Strings.Get("combat_started", { n = 1 }), "Combate: 1 enemigo")
end)

T.case("Latin American Spanish falls back to Spain's table", function()
    T.eq(Strings.SetLanguage("es-419"), "es-419")
    T.eq(Strings.Get("combat_started", { n = 2 }), "Combate: 2 enemigos")
end)

T.case("Russian plural categories", function()
    Strings.SetLanguage("ru")
    T.eq(Strings.Get("meters", { n = 1 }), "1 метр")
    T.eq(Strings.Get("meters", { n = 21 }), "21 метр", "21 is 'one'")
    T.eq(Strings.Get("meters", { n = 3 }), "3 метра", "'few'")
    T.eq(Strings.Get("meters", { n = 12 }), "12 метров", "12 is 'many' (teens)")
    T.eq(Strings.Get("meters", { n = 25 }), "25 метров")
    T.eq(Strings.Get("meters", { n = 0 }), "0 метров")
end)

T.case("Polish plural categories", function()
    Strings.SetLanguage("pl")
    T.eq(Strings.Get("meters", { n = 1 }), "1 metr")
    T.eq(Strings.Get("meters", { n = 2 }), "2 metry")
    T.eq(Strings.Get("meters", { n = 22 }), "22 metry")
    T.eq(Strings.Get("meters", { n = 5 }), "5 metrów")
    T.eq(Strings.Get("meters", { n = 12 }), "12 metrów")
    T.eq(Strings.Get("meters", { n = 21 }), "21 metrów", "in Polish only 1 is 'one'")
end)

T.case("French: 0 and 1 are singular", function()
    Strings.SetLanguage("fr")
    local one = Strings.Get("meters", { n = 1 })
    T.eq(Strings.Get("meters", { n = 0 }):gsub("^0", "1"), one)
    T.truthy(Strings.Get("meters", { n = 2 }) ~= one:gsub("^1", "2"))
end)

T.case("Japanese has no plural forms and its own separators", function()
    Strings.SetLanguage("ja")
    T.eq(Strings.Get("meters", { n = 1 }), "1メートル")
    T.eq(Strings.List({ "a", nil, "b", false, "" }), "a、b")
    T.eq(Strings.Sentences({ "戦闘", "終了。" }), "戦闘。終了。")
end)

T.case("Lists skip empty parts wherever they are", function()
    Strings.SetLanguage("en")
    T.eq(Strings.List({ nil, "a", false, "", "b" }), "a, b")
    T.eq(Strings.List({}), "")
end)

T.case("Sentences add a stop unless the part ends one", function()
    Strings.SetLanguage("en")
    T.eq(Strings.Sentences({ "Hello", "Bye.", "Why?", "Note:  " }), "Hello. Bye. Why? Note:")
    T.eq(Strings.Sentences({ nil, "" }), "")
end)

T.case("Missing keys fall back to English, then to the key itself", function()
    Strings.SetLanguage("es")
    T.eq(Strings.Get("no_such_key_xyz"), "no_such_key_xyz")
    T.truthy(#Test.errors > 0, "a missing string is logged as an error")
    T.eq(Strings.Get("meters", { n = 4 }), "4 metros")
end)

T.case("Unknown language codes use English", function()
    T.eq(Strings.SetLanguage("xx"), "xx")
    T.eq(Strings.Get("meters", { n = 4 }), "4 meters")
end)

T.case("Auto picks the game's language", function()
    Test.language = "Spanish"
    T.eq(Strings.SetLanguage("auto"), "es")
    Test.language = "Nonsense"
    T.eq(Strings.SetLanguage("auto"), "en")
end)

T.case("Placeholders: missing arguments become empty, numbers get one decimal", function()
    Strings.SetLanguage("en")
    T.eq(Strings.Get("resource", { name = "Action", value = 1.26, max = 2 }), "Action 1.3 of 2")
    T.eq(Strings.Get("resource", { name = "Action", value = 1.25, max = 2 }), "Action 1.2 of 2", "exact halves round to even (C printf)")
    T.eq(Strings.Get("resource", { name = "Action" }), "Action  of ")
end)

T.case("Key names", function()
    Strings.SetLanguage("en")
    T.eq(Strings.KeyName("CTRL+R"), "Control R")
    T.eq(Strings.KeyName("SHIFT+RETURN"), "Shift Enter")
    T.eq(Strings.InputName("kp_1", {}), "Numpad 1")
end)
